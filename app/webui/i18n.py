def set_lang(lang) -> None:
    _local.lang = lang if lang in SUPPORTED else "es"


def get_lang() -> str:
    return getattr(_local, "lang", "es")


def tr(key: str, **params) -> str:
    text = MESSAGES[get_lang()].get(key) or MESSAGES["es"].get(key) or key
    return text.format(**params) if params else text
